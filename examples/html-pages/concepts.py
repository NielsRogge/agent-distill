"""Brainstorm the HTML-pages concept dataset with the teacher (DESIGN.md §10).

    uv run python examples/html-pages/concepts.py --per-category 20 --bill-to huggingface --output pilot.jsonl
    uv run python examples/html-pages/concepts.py --per-category 420 --bill-to huggingface \
        --output concepts.jsonl --push nielsr/html-concepts

The teacher (an OpenAI-compatible model on HF Inference Providers, billed to `--bill-to`) writes concepts in batches
per category under the "100 HTML files" rules (stunning, never repetitive, full creative mode). Each batch sees a
sample of titles already written in its category, to push away from repeats. Near-duplicates are then removed
(normalized titles, and word overlap of title + idea), categories are balanced, and every concept gets a stable id
and a split: `--validation` and `--test` concepts per category are held out. The dataset is created private.
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import random
import re
from pathlib import Path
from typing import Any

from agent_distill.rubrics.clients import RouterJudge

CATEGORIES = {
    "interactive toy": "a playful thing to poke, drag, draw or fiddle with",
    "game": "a small complete game with rules, a goal and feedback",
    "generative art": "art generated by code that evolves or responds",
    "tool": "a genuinely useful single-purpose utility",
    "data visualization": "an explorable visualization of an invented or well-known dataset",
    "typography experiment": "letters and words as the main visual material",
    "product page": "a landing page for an imaginary product, brand or event",
    "simulation": "physics, ecosystems, crowds, weather or other systems in motion",
    "music and sound": "an instrument, sequencer or visualizer using the Web Audio API (no audio files)",
    "story": "scrollytelling, a short interactive narrative or an explorable explanation",
    "retro interface": "a homage to an old operating system, device or medium",
    "education": "an interactive explainer that teaches one idea well",
}

PROMPT = """You are brainstorming concepts for single-file HTML pages. Each page will be built by a skilled creative
developer as one self-contained index.html (HTML, CSS and JavaScript inline, no network access, no external assets).
Rules for the pages: look stunning, zero repetitive designs, go full creative mode.

Category: {category} ({description}).

Write {count} new concepts for this category. Make them specific, surprising and varied in subject, mood, visual
style and interaction; each must be buildable in one file without images, fonts or libraries from the network.
Avoid these existing titles and anything close to them: {avoid}

Reply with only a JSON array, one object per concept:
[{{"title": "<2-6 words>", "idea": "<one sentence: what the page is and what makes it special>"}}]"""


def normalize(text: str) -> str:
    return re.sub(r"[^a-z0-9 ]+", "", text.lower()).strip()


def words(concept: dict[str, str]) -> set[str]:
    stop = {"a", "an", "the", "of", "and", "to", "in", "on", "with", "that", "for", "your", "you", "as", "by", "is"}
    return {w for w in normalize(f"{concept['title']} {concept['idea']}").split() if w not in stop and len(w) > 2}


def dedupe(concepts: list[dict[str, str]], threshold: float = 0.5) -> list[dict[str, str]]:
    """Drop exact title repeats and concepts whose word overlap (Jaccard) with a kept one is >= `threshold`."""
    kept: list[dict[str, str]] = []
    titles: set[str] = set()
    kept_words: list[set[str]] = []
    for concept in concepts:
        title = normalize(concept["title"])
        bag = words(concept)
        if not title or title in titles:
            continue
        if any(len(bag & other) / max(1, len(bag | other)) >= threshold for other in kept_words):
            continue
        kept.append(concept)
        titles.add(title)
        kept_words.append(bag)
    return kept


def parse(reply: str) -> list[dict[str, str]]:
    start, end = reply.find("["), reply.rfind("]")
    if start < 0 or end <= start:
        return []
    try:
        items = json.loads(reply[start : end + 1])
    except ValueError:
        return []
    return [
        {"title": str(item["title"]).strip(), "idea": str(item["idea"]).strip()}
        for item in items
        if isinstance(item, dict) and item.get("title") and item.get("idea")
    ]


async def brainstorm(client: RouterJudge, category: str, target: int, batch: int, budget: float,
                     rng: random.Random) -> list[dict[str, str]]:  # fmt: skip
    concepts: list[dict[str, str]] = []
    for _ in range(target // batch * 3 + 3):  # retries for empty or repetitive batches
        if len(concepts) >= target or client.usage.cost_usd >= budget:
            break
        avoid = [c["title"] for c in rng.sample(concepts, min(60, len(concepts)))]
        prompt = PROMPT.format(category=category, description=CATEGORIES[category], count=batch,
                               avoid="; ".join(avoid) or "none yet")  # fmt: skip
        try:
            reply = await client.complete(prompt, [])
        except Exception as exc:  # one failed batch is retried by the loop
            print(f"  {category}: batch failed ({exc})", flush=True)
            continue
        concepts = dedupe(concepts + [{**c, "category": category} for c in parse(reply)])
        print(f"  {category}: {len(concepts)}/{target} (${client.usage.cost_usd:.2f})", flush=True)
    return concepts[:target]


def concept_id(concept: dict[str, str]) -> str:
    return hashlib.sha256(f"{concept['category']}|{normalize(concept['title'])}".encode()).hexdigest()[:12]


def assign_splits(concepts: list[dict[str, Any]], validation: int, test: int, seed: int) -> list[dict[str, Any]]:
    rng = random.Random(seed)
    result = []
    for category in CATEGORIES:
        group = sorted((c for c in concepts if c["category"] == category), key=lambda c: c["concept_id"])
        rng.shuffle(group)
        for index, concept in enumerate(group):
            split = "validation" if index < validation else "test" if index < validation + test else "train"
            result.append({**concept, "split": split})
    return result


def push(rows: list[dict[str, Any]], repo: str) -> None:
    from datasets import Dataset, DatasetDict

    splits = {name: [r for r in rows if r["split"] == name] for name in ("train", "validation", "test")}
    DatasetDict({name: Dataset.from_list(items) for name, items in splits.items() if items}).push_to_hub(
        repo, private=True, commit_message="agent-distill: html-pages concepts"
    )
    print(f"pushed {len(rows)} concepts to {repo} (private)", flush=True)


async def main_async(args: argparse.Namespace) -> None:
    client = RouterJudge(model=args.teacher, bill_to=args.bill_to, price=(args.price_in, args.price_out),
                         max_tokens=args.max_tokens, temperature=1.0, timeout=600)  # fmt: skip
    rng = random.Random(args.seed)
    categories = [c for c in CATEGORIES if not args.categories or c in args.categories]
    per_budget = args.budget_usd / len(categories)
    results = await asyncio.gather(*(brainstorm(client, category, args.per_category, args.batch,
                                                per_budget * (i + 1), rng)
                                     for i, category in enumerate(categories)))  # fmt: skip
    concepts = dedupe([c for group in results for c in group])  # across categories too
    for concept in concepts:
        concept["concept_id"] = concept_id(concept)
    rows = assign_splits(concepts, args.validation, args.test, args.seed)
    args.output.write_text("".join(json.dumps(row) + "\n" for row in rows))
    counts = {c: sum(r["category"] == c for r in rows) for c in categories}
    print(json.dumps({"concepts": len(rows), "per_category": counts, "spent_usd": round(client.usage.cost_usd, 3),
                      "usage": vars(client.usage)}, indent=2))  # fmt: skip
    if args.push:
        push(rows, args.push)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--teacher", default="zai-org/GLM-5.3")
    parser.add_argument("--price-in", type=float, default=1.4, help="USD per 1M input tokens (for the budget)")
    parser.add_argument("--price-out", type=float, default=4.4, help="USD per 1M output tokens")
    parser.add_argument("--bill-to", default="")
    parser.add_argument("--per-category", type=int, default=20)
    parser.add_argument("--batch", type=int, default=25)
    parser.add_argument("--categories", nargs="*", help="Subset of categories")
    parser.add_argument("--validation", type=int, default=10, help="Held-out validation concepts per category")
    parser.add_argument("--test", type=int, default=10, help="Held-out test concepts per category")
    parser.add_argument("--max-tokens", type=int, default=16384)
    parser.add_argument("--budget-usd", type=float, default=2.0)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--push", default="", help="Dataset repo to push to (created private)")
    asyncio.run(main_async(parser.parse_args(argv)))


if __name__ == "__main__":
    main()
